import Fastify from 'fastify';
import jwt from '@fastify/jwt';
import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {config} from '../src/config.ts';
import {pool} from '../src/db.ts';
import {authRoutes} from '../src/routes/auth.ts';
import {chatRoutes} from '../src/routes/chat.ts';
import {coopRoutes} from '../src/routes/coop.ts';
assert.equal(config.NODE_ENV,'development');
assert.ok(['localhost','127.0.0.1','[::1]'].includes(new URL(config.DATABASE_URL).hostname));
const app=Fastify(),suffix=randomBytes(5).toString('hex'),names=['A','B'].map(n=>'Sticker'+n+suffix),emails=names.map(n=>n+'@example.test'),ids=[],tokens=[];
let lobby='';
const call=(method,url,i,payload)=>app.inject({method,url,headers:i==null?{}:{authorization:'Bearer '+tokens[i]},...(payload?{payload}:{})});
const unlocks=i=>call('GET','/v1/chat/stickers',i);
const send=(i,text,channel='world',recipientId)=>call('POST','/v1/chat/messages',i,{channel,text,...(recipientId?{recipientId}:{})});
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const marker='[sticker:ravienna_mythic]';
try{
 await app.register(jwt,{secret:config.JWT_SECRET});await app.register(authRoutes,{prefix:'/v1/auth'});await app.register(chatRoutes,{prefix:'/v1/chat'});await app.register(coopRoutes,{prefix:'/v1/co-op'});await app.ready();
 for(let i=0;i<2;i++){const password=randomBytes(16).toString('hex');assert.equal((await call('POST','/v1/auth/register',null,{email:emails[i],playerName:names[i],password})).statusCode,201);const r=await call('POST','/v1/auth/login',null,{playerName:names[i],password});assert.equal(r.statusCode,200);ids.push(r.json().player.id);tokens.push(r.json().accessToken);}
 assert.equal((await unlocks(null)).statusCode,401);
 assert.deepEqual((await unlocks(0)).json().unlocked,[]);
 assert.deepEqual((await unlocks(1)).json().unlocked,[]);
 assert.equal((await send(0,marker)).json().error,'sticker_locked');
 assert.equal((await send(0,'[sticker:gerald_chibi]')).statusCode,201);
 await pool.query("INSERT INTO friendships(player_id,friend_id,status) VALUES($1,$2,'accepted')",ids);
 assert.equal((await send(0,marker,'private',ids[1])).json().error,'sticker_locked');
 const created=await call('POST','/v1/co-op/lobbies',0,{regionId:'six_zone_willow_fields',maxMembers:4});assert.equal(created.statusCode,201);lobby=created.json().lobbyId;
 assert.ok((await call('POST','/v1/co-op/lobbies/join',1,{inviteCode:created.json().inviteCode})).statusCode<300);
 assert.equal((await send(0,marker,'party')).json().error,'sticker_locked');
 await pool.query("INSERT INTO owned_characters(player_id,char_id) VALUES($1,'ravienna_mythic') ON CONFLICT DO NOTHING",[ids[0]]);
 assert.deepEqual((await unlocks(0)).json().unlocked,['ravienna_mythic']);
 assert.deepEqual((await unlocks(1)).json().unlocked,[]);
 assert.equal((await send(1,marker)).statusCode,403);
 await sleep(1100);
 assert.equal((await send(0,marker)).statusCode,201);
 assert.ok((await call('GET','/v1/chat/messages?channel=world',1)).json().messages.some(m=>m.playerId===ids[0]&&m.text===marker));
 await sleep(1100);
 assert.equal((await send(0,marker,'party')).statusCode,201);
 assert.ok((await call('GET','/v1/chat/messages?channel=party',1)).json().messages.some(m=>m.text===marker));
 await sleep(1100);
 assert.equal((await send(0,marker,'private',ids[1])).statusCode,201);
 assert.equal((await call('GET','/v1/chat/messages?channel=private&recipientId='+ids[0],1)).json().messages[0].text,marker);
 await pool.query("DELETE FROM owned_characters WHERE player_id=$1 AND char_id='ravienna_mythic'",[ids[0]]);
 assert.deepEqual((await unlocks(0)).json().unlocked,[]);
 assert.equal((await send(0,marker)).statusCode,403);
 assert.equal((await call('GET','/v1/chat/messages?channel=private&recipientId='+ids[0],1)).json().messages[0].text,marker);
 console.log('PASS starter availability, ownership unlock/revocation, account isolation, world/party/private delivery, locked sender rejection and recipient history');
}catch(e){console.error(e);process.exitCode=1;}finally{await app.close();if(lobby)await pool.query('DELETE FROM co_op_lobbies WHERE id=$1',[lobby]);await pool.query('DELETE FROM accounts WHERE email=ANY($1)',[emails]);await pool.end();}