 const mod=(token,payload)=>request(token,"/v1/developer/moderation/",payload);
 const act=(name,action,minutes)=>({playerName:name,action,reason:"Automated moderation QA",...(minutes?{minutes}:{})});
 const chat=(token)=>request(token,"/v1/chat/messages",{channel:"world",text:"Moderation QA"});
 const susp=(token,payload)=>request(token,"/v1/developer/moderation/suspensions",payload);
 const action=(name,action,minutes)=>({playerName:name,action,reason:"Automated suspension QA",...(minutes?{minutes}:{})});
 const login=(player,password=player.password)=>app.inject({method:"POST",url:"/v1/auth/login",payload:{playerName:player.name,password}});
 const observer=await create(3);
 const search=(t,q)=>request(t,"/v1/developer/moderation/players?q="+encodeURIComponent(q));
 const detail=(t,id)=>request(t,"/v1/developer/moderation/players/"+id);
 const pid=(await pool.query("SELECT id FROM players WHERE account_id=$1",[b.id])).rows[0].id;
 assert.equal((await search(null,b.name)).statusCode,401);
 assert.equal((await search(b.token,b.name)).statusCode,403);
 await staff(ownerToken,change(a.name,"analyst"));
