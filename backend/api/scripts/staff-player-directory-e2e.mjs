 assert.deepEqual(Object.keys(matches.players[0]).sort(),["id","level","name","status"]);
 assert.equal((await detail(a.token,"invalid")).statusCode,400);
 assert.equal((await detail(a.token,"00000000-0000-4000-8000-000000000000")).statusCode,404);
 const message=await chat(b.token);assert.equal(message.statusCode,201);
 assert.equal((await request(observer.token,"/v1/chat/reports",{messageId:message.json().message.id})).statusCode,201);
 await mod(ownerToken,act(b.name,"warn"));await mod(ownerToken,act(b.name,"mute",30));
 const moderator=(await detail(a.token,pid)).json();
