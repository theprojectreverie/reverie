import Fastify from "fastify";
import jwt from "@fastify/jwt";
import rateLimit from "@fastify/rate-limit";
import websocket from "@fastify/websocket";
import {config} from "../src/config.ts";
import {pool} from "../src/db.ts";
import {trustLocalProxy} from "../src/world/proxy-trust.ts";
import {createSharedRateLimitStore} from "../src/world/shared-rate-limit.ts";
import {gameServerRoutes} from "../src/routes/game-servers.ts";
const app=Fastify({logger:false,trustProxy:trustLocalProxy});
await app.register(rateLimit,{max:5,timeWindow:60000,store:createSharedRateLimitStore(pool,process.env.REVERIE_QA_PROXY_NAMESPACE,config.JWT_SECRET)});
await app.register(jwt,{secret:config.JWT_SECRET});
await app.register(websocket);
app.get("/probe",{config:{rateLimit:false}},async req=>({pid:process.pid,ip:req.ip,protocol:req.protocol}));
app.get("/quota",async()=>({pid:process.pid}));
app.post("/mutation",{config:{rateLimit:false}},async()=>({pid:process.pid}));
app.get("/v1/realtime",{websocket:true,config:{rateLimit:false},preValidation:async req=>{await req.jwtVerify();}},(socket,req)=>{socket.send(JSON.stringify({pid:process.pid,sub:req.user.sub}));});
await app.register(gameServerRoutes,{prefix:"/v1/game-servers"});
app.addHook("onClose",async()=>pool.end());
await app.listen({host:"127.0.0.1",port:0});
process.send({port:app.server.address().port,pid:process.pid});
process.on("message",async m=>{if(m==="stop"){await app.close();process.exit(0);}});
